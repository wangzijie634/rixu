import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

// Import as ESM even before the app's package.json exists.
const source = await readFile(new URL('../dist/lib/calendar.js', import.meta.url), 'utf8');
const calendar = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const { localDate, parseDate, addDays, addMonths, weekDates, monthCells, toMinutes, formatTime, validateTask, findConflicts, layoutTasks, createICalendar, minuteAtOffset, timeRangeFromDrag } = calendar;

assert.equal(localDate(new Date(2026, 9, 21, 0, 5)), '2026-10-21');
assert.equal(parseDate('2026-02-29'), null);
assert.equal(parseDate('2024-02-29')?.getDate(), 29);
assert.equal(parseDate('2026-13-01'), null);
assert.equal(addDays('2024-02-28', 1), '2024-02-29');
assert.equal(addDays('2026-12-31', 1), '2027-01-01');
assert.equal(addMonths('2026-01-31', 1), '2026-02-28');
assert.equal(addMonths('2024-03-31', -1), '2024-02-29');
assert.deepEqual(weekDates('2026-10-25'), ['2026-10-19', '2026-10-20', '2026-10-21', '2026-10-22', '2026-10-23', '2026-10-24', '2026-10-25']);
const cells = monthCells('2026-10-21', '2026-10-21');
assert.equal(cells.length, 42);
assert.equal(cells[0].date, '2026-09-28');
assert.equal(cells.filter(cell => cell.isCurrentMonth).length, 31);
assert.equal(cells.filter(cell => cell.isToday).length, 1);
assert.equal(toMinutes('08:30'), 510);
assert.equal(toMinutes('24:00'), 1440);
assert.ok(Number.isNaN(toMinutes('24:01')));
assert.ok(Number.isNaN(toMinutes('9:00')));
assert.equal(formatTime(1439), '23:59');
assert.equal(formatTime(-1), '');

const task = (id, start, end, extra = {}) => ({ id, title: `任务 ${id}`, date: '2026-10-21', start, end, ...extra });
assert.equal(validateTask(task('a', '09:00', '10:00')).valid, true);
assert.equal(validateTask(task('a', '09:00', '09:00')).valid, false);
assert.equal(validateTask(task('a', '24:00', '24:00')).valid, false);
assert.equal(validateTask(task('a', '23:00', '24:00')).valid, true);
assert.equal(validateTask(task('a', '09:00', '10:00', { title: '  ' })).valid, false);
assert.equal(validateTask(task('a', '09:00', '10:00', { title: '长'.repeat(200), notes: '注'.repeat(10000) })).valid, true);
assert.equal(validateTask(task('a', '09:00', '10:00', { title: '长'.repeat(201) })).valid, false);
assert.equal(validateTask(task('a', '09:00', '10:00', { notes: '注'.repeat(10001) })).valid, false);
const tasks = [task('a', '09:00', '10:00'), task('b', '09:30', '10:30'), task('c', '10:00', '11:00'), task('d', '11:00', '12:00')];
assert.deepEqual(findConflicts(tasks, task('a', '09:00', '10:00')).map(item => item.id), ['b']);
assert.deepEqual(findConflicts(tasks, task('new', '11:00', '12:00')).map(item => item.id), ['d']);
assert.deepEqual(findConflicts(tasks, task('new', '09:00', '10:00', { date: '2026-10-22' })), []);
const before = JSON.stringify(tasks);
const positions = layoutTasks(tasks, { startHour: 8, endHour: 20 });
assert.equal(JSON.stringify(tasks), before);
assert.deepEqual(positions.map(item => [item.id, item.column, item.columns]), [['a', 0, 2], ['b', 1, 2], ['c', 0, 2], ['d', 0, 1]]);
assert.equal(positions[0].top, 60);
assert.equal(positions[0].height, 60);
assert.equal(positions[0].width, 50);
const triple = layoutTasks([task('a', '09:00', '12:00'), task('b', '10:00', '11:00'), task('c', '10:30', '11:30')]);
assert.ok(triple.every(item => item.columns === 3));
const clipped = layoutTasks([task('a', '06:00', '09:00')], { startHour: 8, endHour: 20 });
assert.equal(clipped[0].top, 0);
assert.equal(clipped[0].height, 60);
const shortTasks = [task('short-a', '09:00', '09:05'), task('short-b', '09:05', '09:10')];
assert.deepEqual(layoutTasks(shortTasks).map(item => [item.column, item.columns]), [[0, 1], [0, 1]]);
const expanded = layoutTasks(shortTasks, { startHour: 8, endHour: 20, minDisplayMinutes: 31 });
assert.deepEqual(expanded.map(item => [item.column, item.columns]), [[0, 2], [1, 2]]);
assert.deepEqual(expanded.map(item => [item.top, item.height]), [[60, 5], [65, 5]]);
const touchDisplayBoundary = layoutTasks([task('a', '09:00', '09:05'), task('b', '09:31', '09:36')], { minDisplayMinutes: 31 });
assert.deepEqual(touchDisplayBoundary.map(item => [item.column, item.columns]), [[0, 1], [0, 1]]);
assert.throws(() => layoutTasks(shortTasks, { minDisplayMinutes: -1 }), RangeError);

const output = createICalendar([task('a', '23:00', '24:00', { title: '中文会议,讨论;计划\\内容', notes: '第一行\n第二行' }), task('long', '09:00', '10:00', { title: '中文标题'.repeat(25) })], { now: new Date('2026-10-21T00:00:00Z') });
const unfolded = output.replace(/\r\n /g, '');
assert.ok(unfolded.includes('DTSTART:20261021T230000\r\nDTEND:20261022T000000'));
assert.ok(unfolded.includes('SUMMARY:中文会议\\,讨论\\;计划\\\\内容'));
assert.ok(unfolded.includes('DESCRIPTION:第一行\\n第二行'));
assert.ok(unfolded.includes('DTSTAMP:20261021T000000Z'));
assert.equal((output.match(/BEGIN:VEVENT/g) ?? []).length, 2);
for (const line of output.split('\r\n')) assert.ok(Buffer.byteLength(line, 'utf8') <= 75);
assert.equal(createICalendar([], { now: new Date('2026-10-21T00:00:00Z') }).includes('BEGIN:VEVENT'), false);
assert.doesNotThrow(() => createICalendar([task('imported', '09:00', '10:00', { title: '长'.repeat(200), notes: '注'.repeat(10000) })]));
assert.throws(() => createICalendar([task('bad', '10:00', '09:00')]), RangeError);

assert.equal(minuteAtOffset(0, 1440), 0);
assert.equal(minuteAtOffset(720, 1440), 720);
assert.equal(minuteAtOffset(-20, 1440), 0);
assert.equal(minuteAtOffset(2000, 1440), 1440);
assert.ok(Number.isNaN(minuteAtOffset(10, 0)));

assert.deepEqual(timeRangeFromDrag(14 * 60, 17 * 60), { startMinutes: 840, endMinutes: 1020 });
assert.deepEqual(timeRangeFromDrag(839.9999952904593, 1020.0000000001), { startMinutes: 840, endMinutes: 1020 });
assert.deepEqual(timeRangeFromDrag(845, 1010), { startMinutes: 840, endMinutes: 1020 });
assert.deepEqual(timeRangeFromDrag(863, 863), { startMinutes: 855, endMinutes: 915 });
assert.deepEqual(timeRangeFromDrag(0, 0), { startMinutes: 0, endMinutes: 60 });
assert.deepEqual(timeRangeFromDrag(1435, 1435), { startMinutes: 1380, endMinutes: 1440 });
assert.deepEqual(timeRangeFromDrag(1430, 1435), { startMinutes: 1425, endMinutes: 1440 });
assert.deepEqual(timeRangeFromDrag(849, 855), { startMinutes: 840, endMinutes: 855 });
assert.deepEqual(timeRangeFromDrag(840, 842, { clickThreshold: 0 }), { startMinutes: 840, endMinutes: 855 });
assert.deepEqual(timeRangeFromDrag(-20, 2000), { startMinutes: 0, endMinutes: 1440 });
assert.throws(() => timeRangeFromDrag(0, 60, { step: 0 }), RangeError);
assert.throws(() => timeRangeFromDrag(NaN, 60), RangeError);
console.log('calendar: 日期、导航、拖动选区、任务校验、冲突、重叠布局与 iCalendar 测试通过');
